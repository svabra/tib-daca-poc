import { TestBed } from '@angular/core/testing';
import { DacaReleaseHistoryComponent } from '../../../../../../packages/design-system/src/lib/release-history.component';
import { DACA_VERSION } from '../../../../../../packages/design-system/src/lib/version';
import { dacaReleaseHistory } from '../../../../../../packages/design-system/src/lib/release-history';

describe('DaCa release history', () => {
  it('shows tagged releases and filters by feature or tag', async () => {
    await TestBed.configureTestingModule({ imports: [DacaReleaseHistoryComponent] }).compileComponents();
    const fixture = TestBed.createComponent(DacaReleaseHistoryComponent);
    fixture.componentRef.setInput('locale', 'de');
    fixture.detectChanges();
    expect(fixture.nativeElement.textContent).toContain(`V${DACA_VERSION}`);
    expect(fixture.nativeElement.textContent).toContain('V0.1.28');
    expect(fixture.nativeElement.textContent).toContain('Strukturinventare importieren und verwalten');
    expect(fixture.nativeElement.textContent).toContain('V0.1.29');
    const releases = dacaReleaseHistory('catalog', 'de');
    expect(releases[0]?.version).toBe(DACA_VERSION);
    expect(releases.find(release => release.version === '0.2.0')?.features.some(feature => feature.title === 'Domänen an andere Personen abtreten')).toBe(true);
    expect(releases[0]?.features.some(feature => feature.tags.includes('Views'))).toBe(true);
    expect(releases.find(release => release.version === '0.2.1')?.features.some(feature => feature.tags.includes('Amtsfilter'))).toBe(true);
    expect(releases[0]?.features.some(feature => feature.tags.includes('CPS'))).toBe(true);
    expect(releases.some(release => ['0.3.0','0.3.1'].includes(release.version))).toBe(false);
    expect(releases.find(release => release.version === '0.1.32')?.features.some(feature => feature.title === 'AdA-Import-Journey wiederholen')).toBe(true);
    expect(releases[0]?.features.some(feature => feature.title === 'AdA-Import-Journey wiederholen')).toBe(false);
    const previous = dacaReleaseHistory('catalog', 'de').find(release => release.version === '0.1.30');
    expect(previous?.features).toHaveLength(6);
    expect(previous?.features[0].title).toBe('Physische Modelle aus CSV laden');
    expect(fixture.nativeElement.textContent).toContain('Feldbearbeitung und Co-Design');
    expect(fixture.nativeElement.textContent).toContain('V0.1.1');
    expect(dacaReleaseHistory('catalog', 'de').every((release) => release.features.every((feature) => feature.tags.length > 0))).toBe(true);
    expect(dacaReleaseHistory('control-plane', 'en')[0]?.features.some((feature) => feature.title.includes('field'))).toBe(false);
    const search = fixture.nativeElement.querySelector('input[type="search"]') as HTMLInputElement;
    search.value = 'Datenmodelle';
    search.dispatchEvent(new Event('input'));
    fixture.detectChanges();
    expect(fixture.nativeElement.textContent).toContain('Mit einer vorhandenen Tabelle starten');
    expect(fixture.nativeElement.textContent).not.toContain('Verbesserungen schneller finden');
    search.value = 'nicht vorhanden';
    search.dispatchEvent(new Event('input'));
    fixture.detectChanges();
    expect(fixture.nativeElement.textContent).toContain('Keine passenden Änderungen gefunden');
  });
});
